-- Atomically record one sighting of a GS1 (01)+(21) pair and return the
-- aggregate the duplicate-serial check needs — never the raw reporter keys.
-- Executable by the service role only: with the public anon key anyone could
-- otherwise forge sightings and make a genuine pack look cloned.
CREATE OR REPLACE FUNCTION record_medicine_serial(
  p_gtin text,
  p_serial text,
  p_batch text DEFAULT NULL,
  p_reporter text DEFAULT NULL,
  p_area text DEFAULT NULL
)
RETURNS TABLE (total_scans int, distinct_reporters int, distinct_areas int, first_seen timestamptz)
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
BEGIN
  INSERT INTO "MedicineSerial" (gtin, serial, batch, reporter_keys, areas)
  VALUES (
    p_gtin,
    p_serial,
    p_batch,
    CASE WHEN p_reporter IS NULL THEN ARRAY[]::text[] ELSE ARRAY[p_reporter] END,
    CASE WHEN p_area IS NULL THEN ARRAY[]::text[] ELSE ARRAY[p_area] END
  )
  ON CONFLICT (gtin, serial) DO UPDATE SET
    scan_count    = "MedicineSerial".scan_count + 1,
    last_seen_at  = CURRENT_TIMESTAMP,
    batch         = COALESCE("MedicineSerial".batch, EXCLUDED.batch),
    reporter_keys = CASE
                      WHEN p_reporter IS NULL OR p_reporter = ANY("MedicineSerial".reporter_keys)
                        THEN "MedicineSerial".reporter_keys
                      ELSE array_append("MedicineSerial".reporter_keys, p_reporter)
                    END,
    areas         = CASE
                      WHEN p_area IS NULL OR p_area = ANY("MedicineSerial".areas)
                        THEN "MedicineSerial".areas
                      ELSE array_append("MedicineSerial".areas, p_area)
                    END;

  RETURN QUERY
    SELECT m.scan_count, cardinality(m.reporter_keys), cardinality(m.areas), m.first_seen_at::timestamptz
    FROM "MedicineSerial" m
    WHERE m.gtin = p_gtin AND m.serial = p_serial;
END;
$$;

REVOKE ALL ON FUNCTION record_medicine_serial(text, text, text, text, text) FROM PUBLIC, anon, authenticated;
GRANT EXECUTE ON FUNCTION record_medicine_serial(text, text, text, text, text) TO service_role;

